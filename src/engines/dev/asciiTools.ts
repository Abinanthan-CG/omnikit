export type AsciiStyle = 'block' | 'slant' | 'box';

export function generateAsciiBanner(text: string, style: AsciiStyle = 'block'): string {
  if (!text) return '';

  const chars = text.toUpperCase().split('');
  const height = 5;
  const lines: string[] = Array(height).fill('');

  for (const ch of chars) {
    const glyph = BLOCK_FONT[ch] || BLOCK_FONT['?'];
    for (let row = 0; row < height; row++) {
      let segment = glyph[row];
      if (style === 'slant') {
        segment = segment.replace(/█/g, '/');
      } else if (style === 'box') {
        segment = segment.replace(/█/g, '#');
      }
      lines[row] += segment;
    }
  }

  return lines.join('\n');
}
